from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
import math
from pathlib import Path
import random
import statistics
import unittest


def validate(image):
    """Validate finite, rectangular, bounded grayscale images; return shape."""
    if not image or len(image) > 256 or not image[0] or len(image[0]) > 256:
        raise ValueError("image dimensions must be 1..256")
    width = len(image[0])
    if any(len(row) != width for row in image):
        raise ValueError("ragged image")
    if any(isinstance(x, bool) or not isinstance(x, (int, float)) or
           not math.isfinite(x) or not 0 <= x <= 1 for row in image for x in row):
        raise ValueError("pixels must be finite numbers in [0,1]")
    return len(image), width


@dataclass(frozen=True)
class SpatialNormal:
    height: int
    width: int
    means: tuple[float, ...]
    scales: tuple[float, ...]

    @classmethod
    def fit(cls, images, floor=0.01):
        if not math.isfinite(floor) or floor <= 0:
            raise ValueError("positive finite scale floor required")
        if not 2 <= len(images) <= 512:
            raise ValueError("fit requires 2..512 normal images")
        shape = validate(images[0])
        for image in images:
            if validate(image) != shape:
                raise ValueError("inconsistent training shape")
        flat = [tuple(x for row in image for x in row) for image in images]
        columns = tuple(zip(*flat))
        return cls(*shape, tuple(statistics.mean(c) for c in columns),
                   tuple(max(floor, statistics.stdev(c)) for c in columns))

    def heatmap(self, image, standardized=True):
        if validate(image) != (self.height, self.width):
            raise ValueError("inference shape differs from training")
        flat = tuple(x for row in image for x in row)
        scores = [abs(x - mu) / (s if standardized else 1.0)
                  for x, mu, s in zip(flat, self.means, self.scales)]
        return [scores[y*self.width:(y+1)*self.width] for y in range(self.height)]


def max_score(heatmap):
    return max(max(row) for row in heatmap)


def calibrate(model, normal_images, alpha=0.05, standardized=True):
    """Nearest-rank empirical (1-alpha) quantile of NORMAL image maxima.

    Strict > comparison retains ties as normal. No test labels are consumed.
    Finite-sample empirical calibration is not a future-risk guarantee.
    """
    if not normal_images or not math.isfinite(alpha) or not 0 < alpha < 1:
        raise ValueError("nonempty calibration and alpha in (0,1) required")
    scores = sorted(max_score(model.heatmap(im, standardized)) for im in normal_images)
    return scores[math.ceil((1-alpha)*len(scores))-1]


def specimen(seed, size=24, defect=None):
    """Original aligned texture, heteroscedastic noise, optional exact defect mask."""
    if isinstance(size, bool) or not isinstance(size, int) or not 12 <= size <= 64:
        raise ValueError("synthetic size must be an integer in 12..64")
    if defect not in (None, "spot", "scratch"):
        raise ValueError("unknown defect")
    rng = random.Random(seed)
    image = [[min(1.0, max(0.0, .45 + .12*math.sin(x*.7) +
               .08*math.cos(y*.5) + rng.gauss(0, .008 if x < size//2 else .035)))
              for x in range(size)] for y in range(size)]
    mask = [[False]*size for _ in range(size)]
    if defect:
        x0, y0 = rng.randrange(2, size-6), rng.randrange(2, size-6)
        h, w = (4, 4) if defect == "spot" else (6, 1)
        for y in range(y0, y0+h):
            for x in range(x0, x0+w):
                image[y][x] = min(1.0, image[y][x]+.35) if defect == "spot" else 0.0
                mask[y][x] = True
    return image, mask


def experiment():
    train_seeds = list(range(1000, 1048))
    calibration_seeds = list(range(10000, 10032))
    normal_seeds = list(range(30000, 30032))
    defect_seeds = list(range(40000, 40032))
    train = [specimen(s)[0] for s in train_seeds]
    calibration = [specimen(s)[0] for s in calibration_seeds]
    model = SpatialNormal.fit(train)
    test = [(specimen(s)[0], None) for s in normal_seeds]
    test += [specimen(s, defect="spot" if i % 2 == 0 else "scratch")
             for i, s in enumerate(defect_seeds)]
    comparisons = {}
    for standardized in (False, True):
        threshold = calibrate(model, calibration, standardized=standardized)
        tp = fp = tn = fn = 0
        ious = []
        for image, mask in test:
            scores = model.heatmap(image, standardized)
            detected = max_score(scores) > threshold
            if mask is None:
                fp += int(detected)
                tn += int(not detected)
            else:
                tp += int(detected)
                fn += int(not detected)
                predicted = [s > threshold for row in scores for s in row]
                truth = [v for row in mask for v in row]
                intersection = sum(a and b for a, b in zip(predicted, truth))
                union = sum(a or b for a, b in zip(predicted, truth))
                ious.append(intersection/union)
        comparisons["standardized" if standardized else "raw_residual"] = {
            "threshold": threshold, "tp": tp, "fp": fp, "tn": tn, "fn": fn,
            "defect_mean_iou": statistics.mean(ious),
            "normal_image_false_positive_rate": fp/len(normal_seeds),
            "defect_recall": tp/len(defect_seeds),
        }
    return {"schema_version": 1, "scope": "aligned synthetic textures only",
            "protocol": {"train_seeds": train_seeds,
                         "normal_calibration_seeds": calibration_seeds,
                         "test_normal_seeds": normal_seeds,
                         "test_defect_seeds": defect_seeds,
                         "image_size": 24, "alpha": .05,
                         "defects": "alternating spot, scratch; 16 each",
                         "scale_floor": .01}, "comparisons": comparisons}


def local_html():
    """A real computed local result visualization, not interactive/live inference."""
    model = SpatialNormal.fit([specimen(s)[0] for s in range(1000, 1048)])
    image, mask = specimen(40000, defect="spot")
    scores = model.heatmap(image)
    panels = []
    for title, grid, maximum in (("Input", image, 1),
                                 ("Absolute standardized residual", scores, max_score(scores)),
                                 ("Known defect mask", mask, 1)):
        rects = []
        for y, row in enumerate(grid):
            for x, value in enumerate(row):
                intensity = round(255*min(1, value/maximum))
                rects.append(f'<rect x="{x}" y="{y}" width="1" height="1" '
                             f'fill="rgb({intensity},0,{255-intensity})"/>')
        panels.append(f'<section><h2>{title}</h2><svg viewBox="0 0 24 24" '
                      f'width="288" height="288">{"".join(rects)}</svg></section>')
    return ('<!doctype html><html lang="en"><meta charset="utf-8">'
            '<title>Anomaly Inspection Lab</title><h1>Anomaly Inspection Lab</h1>'
            '<p>Computed CPU result on one synthetic image. Saved-output visualization, '
            'not live inference or an industrial benchmark.</p>' + ''.join(panels) + '</html>')


class CoreTests(unittest.TestCase):
    def test_independent_sample_statistics(self):
        model = SpatialNormal.fit([[[.1]], [[.3]]], floor=.001)
        self.assertAlmostEqual(model.means[0], .2)
        self.assertAlmostEqual(model.scales[0], math.sqrt(.02))
        self.assertAlmostEqual(model.heatmap([[.5]])[0][0], .3/math.sqrt(.02))

    def test_constant_floor_and_exact_match(self):
        model = SpatialNormal.fit([[[.2]], [[.2]]])
        self.assertEqual(model.heatmap([[.2]]), [[0.0]])
        self.assertAlmostEqual(model.heatmap([[.3]])[0][0], 10.0)

    def test_invalid_images_and_shapes(self):
        for image in ([], [[]], [[1],[1,0]], [[float("nan")]], [[2]], [[True]]):
            with self.assertRaises(ValueError):
                validate(image)
        with self.assertRaises(ValueError):
            SpatialNormal.fit([[[0]]])
        with self.assertRaises(ValueError):
            SpatialNormal.fit([[[0]], [[0, 0]]])
        with self.assertRaises(ValueError):
            SpatialNormal.fit([[[0]], [[0]]], floor=0)
        with self.assertRaises(ValueError):
            SpatialNormal.fit([[[0]], [[0]]]).heatmap([[0, 0]])

    def test_empirical_quantile_and_ties(self):
        model = SpatialNormal.fit([[[0]], [[0]]])
        normal = [[[x/100]] for x in range(1, 11)]
        threshold = calibrate(model, normal, alpha=.2)
        self.assertAlmostEqual(threshold, 8)
        self.assertEqual(sum(max_score(model.heatmap(im)) > threshold for im in normal), 2)
        for alpha in (0, 1, float("nan")):
            with self.assertRaises(ValueError):
                calibrate(model, normal, alpha)
        with self.assertRaises(ValueError):
            calibrate(model, [])

    def test_generator_and_mask_are_exact(self):
        clean, _ = specimen(42)
        for defect, pixels in (("spot", 16), ("scratch", 6)):
            image, mask = specimen(42, defect=defect)
            self.assertEqual(sum(map(sum, mask)), pixels)
            self.assertTrue(all((a != b) == m for ra, rb, rm in zip(clean, image, mask)
                                for a, b, m in zip(ra, rb, rm)))
            self.assertEqual((image, mask), specimen(42, defect=defect))

    def test_inputs_are_not_mutated(self):
        images = [specimen(i)[0] for i in (1, 2, 3)]
        before = json.dumps(images)
        model = SpatialNormal.fit(images)
        model.heatmap(images[0])
        calibrate(model, images)
        self.assertEqual(json.dumps(images), before)

    def test_controlled_localization_and_split_separation(self):
        report = experiment()
        protocol = report["protocol"]
        names = ("train_seeds", "normal_calibration_seeds", "test_normal_seeds",
                 "test_defect_seeds")
        for i, name in enumerate(names):
            for other in names[i+1:]:
                self.assertFalse(set(protocol[name]) & set(protocol[other]))
        result = report["comparisons"]["standardized"]
        self.assertEqual(result["tp"]+result["fn"], 32)
        self.assertEqual(result["fp"]+result["tn"], 32)
        self.assertGreater(result["defect_mean_iou"], .5)
        self.assertEqual(report, experiment())

    def test_local_view_contains_computed_panels(self):
        page = local_html()
        self.assertEqual(page.count("<svg "), 3)
        self.assertEqual(page.count("<rect "), 3*24*24)
        self.assertIn("not live inference", page)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--html", type=Path, help="create a NEW local visualization file")
    args = parser.parse_args()
    if args.self_test:
        result = unittest.TextTestRunner(verbosity=2).run(
            unittest.defaultTestLoader.loadTestsFromTestCase(CoreTests))
        return 0 if result.wasSuccessful() else 1
    report = experiment()
    if args.html:
        with args.html.open("x", encoding="utf-8") as output:
            output.write(local_html())
    print(json.dumps(report, indent=2, sort_keys=True, allow_nan=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
